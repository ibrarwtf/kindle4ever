"""Root CA tooling for k4fetch (stdlib only).

  gen_roots.py extract CACERT_PEM ROOTS_TXT OUT_DIR   pick labelled certs out of the Mozilla bundle
  gen_roots.py anchors ROOTS_DIR OUT_C                write a BearSSL br_x509_trust_anchor table

The anchors are built the same way BearSSL's `brssl ta` does: raw subject DN,
CA flag, and the RSA modulus/exponent or EC curve/point from the public key.
"""
import base64, glob, os, re, sys

def der_read(b, i):
    """Return (tag, content_start, content_end) of the TLV at offset i."""
    tag = b[i]; i += 1
    ln = b[i]; i += 1
    if ln & 0x80:
        n = ln & 0x7f
        ln = int.from_bytes(b[i:i + n], 'big'); i += n
    return tag, i, i + ln

def children(b, start, end):
    out, i = [], start
    while i < end:
        tag, s, e = der_read(b, i)
        out.append((tag, i, s, e))
        i = e
    return out

def oid_str(data):
    first = data[0]
    parts = [first // 40, first % 40]
    v = 0
    for c in data[1:]:
        v = (v << 7) | (c & 0x7f)
        if not c & 0x80:
            parts.append(v); v = 0
    return '.'.join(map(str, parts))

CURVES = {'1.2.840.10045.3.1.7': 'BR_EC_secp256r1', '1.3.132.0.34': 'BR_EC_secp384r1', '1.3.132.0.35': 'BR_EC_secp521r1'}

def parse_cert(der):
    _, s, e = der_read(der, 0)                       # Certificate
    tbs = children(der, s, e)[0]
    f = children(der, tbs[2], tbs[3])
    if f[0][0] == 0xa0: f = f[1:]                    # skip [0] version
    # serial, sigAlg, issuer, validity, subject, spki
    subj = f[4]; spki = f[5]
    dn = der[subj[1]:subj[3]]                        # full Name TLV
    alg, bits = children(der, spki[2], spki[3])
    algf = children(der, alg[2], alg[3])
    oid = oid_str(der[algf[0][2]:algf[0][3]])
    key = der[bits[2] + 1:bits[3]]                   # BIT STRING minus unused-bits byte
    if oid == '1.2.840.113549.1.1.1':                # rsaEncryption
        _, s2, e2 = der_read(key, 0)
        n, ex = children(key, s2, e2)
        strip = lambda x: x.lstrip(b'\x00')
        return dn, ('rsa', strip(key[n[2]:n[3]]), strip(key[ex[2]:ex[3]]))
    if oid == '1.2.840.10045.2.1':                   # id-ecPublicKey
        curve = oid_str(der[algf[1][2]:algf[1][3]])
        return dn, ('ec', CURVES[curve], key)
    raise ValueError('unsupported key type ' + oid)

def pem_blocks(text):
    return [base64.b64decode(''.join(m.split())) for m in
            re.findall(r'-----BEGIN CERTIFICATE-----(.*?)-----END CERTIFICATE-----', text, re.S)]

def extract(cacert, roots_txt, out_dir):
    text = open(cacert, encoding='utf-8').read()
    asof = re.search(r'Certificate data from Mozilla as of: (.*)', text)
    labels = [l.strip() for l in open(roots_txt, encoding='utf-8') if l.strip() and not l.startswith('#')]
    os.makedirs(out_dir, exist_ok=True)
    for old in glob.glob(os.path.join(out_dir, '*.pem')): os.remove(old)
    for label in labels:
        m = re.search(r'^' + re.escape(label) + r'\n=+\n(?:#[^\n]*\n)*(-----BEGIN CERTIFICATE-----.*?-----END CERTIFICATE-----)', text, re.S | re.M)
        if not m: sys.exit('label not found in bundle: ' + label)
        name = re.sub(r'[^A-Za-z0-9]+', '_', label).strip('_') + '.pem'
        with open(os.path.join(out_dir, name), 'w', newline='\n') as f:
            f.write('# %s\n# Source: Mozilla CA bundle via https://curl.se/ca/cacert.pem (as of %s)\n%s\n'
                    % (label, asof.group(1) if asof else '?', m.group(1)))
        print('  ' + name)

def c_bytes(name, data):
    rows = [', '.join('0x%02X' % c for c in data[i:i + 12]) for i in range(0, len(data), 12)]
    return 'static const unsigned char %s[] = {\n\t%s\n};\n' % (name, ',\n\t'.join(rows))

def anchors(roots_dir, out_c):
    files = sorted(glob.glob(os.path.join(roots_dir, '*.pem')))
    out = ['/* Generated by src/k4fetch/gen_roots.py from the PEM files in src/k4fetch/roots - do not edit. */',
           '#include "bearssl.h"', '']
    entries = []
    for k, path in enumerate(files):
        label = open(path, encoding='utf-8').readline().lstrip('# ').strip()
        dn, key = parse_cert(pem_blocks(open(path, encoding='utf-8').read())[0])
        out.append('/* %s */' % label)
        out.append(c_bytes('TA%d_DN' % k, dn))
        if key[0] == 'rsa':
            out.append(c_bytes('TA%d_RSA_N' % k, key[1]))
            out.append(c_bytes('TA%d_RSA_E' % k, key[2]))
            entries.append('\t{ { (unsigned char *)TA%d_DN, sizeof TA%d_DN }, BR_X509_TA_CA, { BR_KEYTYPE_RSA, '
                           '{ .rsa = { (unsigned char *)TA%d_RSA_N, sizeof TA%d_RSA_N, (unsigned char *)TA%d_RSA_E, sizeof TA%d_RSA_E } } } }'
                           % (k, k, k, k, k, k))
        else:
            out.append(c_bytes('TA%d_EC_Q' % k, key[2]))
            entries.append('\t{ { (unsigned char *)TA%d_DN, sizeof TA%d_DN }, BR_X509_TA_CA, { BR_KEYTYPE_EC, '
                           '{ .ec = { %s, (unsigned char *)TA%d_EC_Q, sizeof TA%d_EC_Q } } } }' % (k, k, key[1], k, k))
    out.append('const br_x509_trust_anchor KFETCH_TAs[] = {\n%s\n};\n' % ',\n'.join(entries))
    out.append('const size_t KFETCH_TAs_NUM = %d;\n' % len(entries))
    with open(out_c, 'w', newline='\n') as f: f.write('\n'.join(out))
    print('  %d trust anchors -> %s' % (len(entries), out_c))

if __name__ == '__main__':
    if len(sys.argv) == 5 and sys.argv[1] == 'extract': extract(*sys.argv[2:])
    elif len(sys.argv) == 4 and sys.argv[1] == 'anchors': anchors(*sys.argv[2:])
    else: sys.exit(__doc__)
